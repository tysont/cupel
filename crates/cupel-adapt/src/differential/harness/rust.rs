pub(super) fn prepare(call: &Call<'_>, site: &Site<'_>) -> Result<Prepared, Problem> {
    let source = site.tree.join(&call.entry.file);
    let (crate_dir, name) = owning_crate(site.tree, &source)?;
    let module = module_path(&crate_dir, &source)?;
    let manifest = format!(
        "[package]\nname = \"{PACKAGE}\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [dependencies]\nentry = {{ package = \"{name}\", path = {} }}\n\n[workspace]\n",
        toml::Value::String(crate_dir.to_string_lossy().into_owned())
    );
    let manifest = write(site, "Cargo.toml", &manifest)?;
    write(
        site,
        "src/main.rs",
        &TEMPLATE.replace("__CALL__", &call_body(call, &module)),
    )?;
    if let Some(lock) = lock_file(site.tree, &crate_dir) {
        let _ = fs::copy(lock, site.work.join("Cargo.lock"));
    }
    let target = site.target.to_string_lossy().into_owned();
    build(
        &Process::new("cargo", &crate_dir)
            .args([
                "build",
                "--quiet",
                "--manifest-path",
                &manifest.to_string_lossy(),
            ])
            .env("CARGO_TARGET_DIR", &target),
        site.cancel,
    )?;
    let binary = site.target.join("debug").join(PACKAGE);
    let process = Process::new(&binary.to_string_lossy(), &crate_dir);
    Ok(Prepared::new(process, site.work.clone()))
}

/// The crate whose `Cargo.toml` is nearest `source` within `tree`, and its package name.
fn owning_crate(tree: &Path, source: &Path) -> Result<(PathBuf, String), Problem> {
    let mut dir = source.parent();
    while let Some(current) = dir.filter(|current| current.starts_with(tree)) {
        let manifest = current.join("Cargo.toml");
        if let Some(name) = fs::read_to_string(&manifest)
            .ok()
            .and_then(|text| text.parse::<toml::Table>().ok())
            .and_then(|table| Some(table.get("package")?.get("name")?.as_str()?.to_owned()))
        {
            return Ok((current.to_path_buf(), name));
        }
        dir = current.parent();
    }
    Err(Problem::Skip(
        "no Cargo.toml with a [package] holds the entry's file".to_owned(),
    ))
}

/// The module path of `source` in the library of the crate at `crate_dir`: `src/lib.rs` is the
/// root, `src/a/mod.rs` and `src/a.rs` are `a`.
fn module_path(crate_dir: &Path, source: &Path) -> Result<String, Problem> {
    let relative = source.strip_prefix(crate_dir.join("src")).map_err(|_| {
        Problem::Skip("the entry's file is not under its crate's `src/`".to_owned())
    })?;
    let text = relative.to_string_lossy().replace('\\', "/");
    if text == "main.rs" || text.starts_with("bin/") {
        return Err(Problem::Skip(
            "the entry is in a binary target; the harness calls a library's functions".to_owned(),
        ));
    }
    let stem = text.strip_suffix(".rs").unwrap_or(&text);
    let stem = stem.strip_suffix("/mod").unwrap_or(stem);
    Ok(if stem == "lib" {
        String::new()
    } else {
        stem.replace('/', "::")
    })
}

/// The `Cargo.lock` nearest the crate, up to the tree's root.
fn lock_file(tree: &Path, crate_dir: &Path) -> Option<PathBuf> {
    crate_dir
        .ancestors()
        .take_while(|dir| dir.starts_with(tree))
        .map(|dir| dir.join("Cargo.lock"))
        .find(|lock| lock.is_file())
}

/// Decodes each argument into an owned value, calls `entry::<module>::<function>`, and returns
/// the result's `Debug` text.
fn call_body(call: &Call<'_>, module: &str) -> String {
    let (decoded, args): (Vec<String>, Vec<String>) = call
        .signature
        .params
        .iter()
        .enumerate()
        .map(|(at, param)| {
            let (owned, borrowed) = rust_owned(&param.text);
            let reference = if borrowed { "&" } else { "" };
            (
                format!("    let a{at}: {owned} = FromJson::from_json(&args[{at}]);\n"),
                format!("{reference}a{at}"),
            )
        })
        .unzip();
    let path: Vec<&str> = ["entry", module, &call.entry.function]
        .into_iter()
        .filter(|part| !part.is_empty())
        .collect();
    format!(
        "{}    format!(\"{{:?}}\", {}({}))\n",
        decoded.concat(),
        path.join("::"),
        args.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::differential::entry::{Resolved, parse};
    use crate::differential::types;
    use cupel_core::syntax::SymbolKey;

    #[test]
    fn modules_follow_the_files_under_src() {
        let crate_dir = Path::new("/r/ledger");
        let module = |file: &str| module_path(crate_dir, &crate_dir.join(file));
        assert_eq!(module("src/lib.rs").unwrap(), "");
        assert_eq!(module("src/money/mod.rs").unwrap(), "money");
        assert_eq!(module("src/money/round.rs").unwrap(), "money::round");
        assert!(matches!(module("src/main.rs"), Err(Problem::Skip(_))));
        assert!(matches!(module("tests/it.rs"), Err(Problem::Skip(_))));
    }

    #[test]
    fn borrowed_arguments_are_decoded_owned_and_passed_by_reference() {
        let entry = parse("src/money/round.rs:split").unwrap();
        let resolved = Resolved {
            symbol: SymbolKey {
                file: entry.file.clone(),
                line: 1,
                col: 1,
            },
            namespace: String::new(),
            signature: "(_: &[i64], _: &str, _: u8) -> Vec<i64>".to_owned(),
        };
        let signature = types::rust(&resolved.signature).unwrap();
        let call = Call {
            entry: &entry,
            resolved: &resolved,
            signature: &signature,
        };
        assert_eq!(
            call_body(&call, "money::round"),
            "    let a0: Vec<i64> = FromJson::from_json(&args[0]);\n\
             \x20   let a1: String = FromJson::from_json(&args[1]);\n\
             \x20   let a2: u8 = FromJson::from_json(&args[2]);\n\
             \x20   format!(\"{:?}\", entry::money::round::split(&a0, &a1, a2))\n"
        );
    }
}
